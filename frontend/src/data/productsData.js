// Quick helper to fetch product by slug
export function getProductBySlug(slug) {
  if (!slug) return null;
  const cleanSlug = slug.replace(/^\/|\/$/g, '').replace(/^product\//, '');
  return productsData[cleanSlug] || null;
}

// Quick helper to fetch category by slug
export function getCategoryBySlug(slug) {
  if (!slug) return null;
  const cleanSlug = slug.replace(/^\/|\/$/g, '').replace(/^product-category\//, '');
  return categoriesData.find(c => c.slug === cleanSlug) || null;
}
